// Свой вопрос в редакторе: node scripts/e2e-own-question.mjs [baseUrl] — встаёт после текущего, курсор в ответе,
// переживает перезагрузку, удаляется с подтверждением и возвращает к предыдущему вопросу.
import { chromium } from "playwright";
const [base = "http://localhost:3000"] = process.argv.slice(2);
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || "/opt/pw-browsers/chromium-1194/chrome-linux/chrome" });
const page = await (await browser.newContext({ viewport: { width: 1440, height: 1000 } })).newPage();
const errors = [];
page.on("pageerror", (e) => errors.push(e.message));
await page.goto(`${base}/register?theme=love`);
await page.fill("#name", "Свой");
await page.fill("#email", `own${Date.now()}@test.local`);
await page.fill("#password", "secret123");
await page.check("input[name=consent]");
await page.click("button[type=submit]");
await page.waitForURL(/\/books\/new/);
await page.fill("#recipientName", "Али");
await page.click("button[type=submit]");
await page.waitForURL(/\/books\/[0-9a-f-]{36}$/);
await page.goto(page.url() + "/questions?q=3");
await page.fill("#answer", "Ответ на третий");
await page.getByRole("button", { name: "Свой вопрос" }).click();
await page.getByPlaceholder(/./).last().waitFor();
const input = page.locator("form input[required]");
await input.fill("Мой собственный вопрос?");
await page.locator("form button.btn-primary").click();
await page.waitForFunction(() => new URL(location.href).searchParams.get("q") === "4");
const h1 = await page.locator("h1").first().innerText();
await page.waitForTimeout(300);
const focused = await page.evaluate(() => document.activeElement?.id);
await page.reload();
const afterReload = await page.locator("h1").first().innerText();
page.once("dialog", (d) => d.accept());
await page.getByRole("button", { name: "Удалить" }).click();
const confirm = page.getByRole("button", { name: "Удалить" }).last();
await confirm.click().catch(() => {});
await page.waitForFunction(() => new URL(location.href).searchParams.get("q") === "3");
const back = await page.inputValue("#answer");
console.log(JSON.stringify({ h1, focused, afterReload, back, errors }));
await browser.close();
process.exit(h1 === "Мой собственный вопрос?" && afterReload === h1 && focused === "answer" && back === "Ответ на третий" && !errors.length ? 0 : 1);
