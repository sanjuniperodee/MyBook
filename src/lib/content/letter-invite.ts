/**
 * Свой текст приглашения близких (books.invite_text): заменяет текст по умолчанию на странице письма и в сообщении со
 * ссылкой. Нужен, когда «её получит …» не подходит — например, книга в память о бабушке, которой уже нет.
 */
export const INVITE_TEXT_MAX = 500;

/**
 * Получатель, которого показывать близким: у автобиографии его нет, а со своим текстом приглашения его имя нигде
 * не подставляем («… прочитает его на страницах книги») — автор сам решил, как сказать о книге.
 */
export const inviteRecipient = (kind: string, recipient: string, inviteText: string) => (kind === "autobiography" || inviteText.trim() ? "" : recipient.trim());
