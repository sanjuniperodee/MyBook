/**
 * Отбивки между блоками текста в HTML — как у react-pdf. У react-pdf поля блоков не схлопываются (соседние
 * складываются), а поле снизу неделимого блока должно поместиться на полосе вместе с ним; браузер соседние поля
 * схлопывает (берёт большее), а поле в конце колонки отбрасывает. Поэтому:
 *  - у неделимых блоков (ряд фото, карточка QR, цитата) отбивка снизу — полем внутри, с пометкой GAP_BELOW
 *    (для замера доводки это внешнее поле, как у PDF);
 *  - отбивка сверху — тоже полем внутри (gapAbove): не отбрасывается в начале колонки и складывается с полем
 *    снизу прошлого блока, как у react-pdf.
 */

/** Пометка блока, у которого отбивка снизу — поле внутри (для замера доводки это внешнее поле, как у PDF). */
export const GAP_BELOW = { "data-gap-below": "" } as const;

/**
 * Отбивка сверху — полем внутри блока, а не внешним (gap — pt): react-pdf отступ сверху у блока, перенесённого на новую
 * полосу, оставляет, а браузер в колонках его отбрасывает; и с полем снизу прошлого блока он складывается, а не
 * схлопывается. Пометка data-gap-above — для замера доводки: это внешнее поле, как у PDF.
 */
export function gapAbove(gap: number, pt: (v: number) => string): { style: { paddingTop?: string }; attrs: Record<string, string> } {
  return gap > 0 ? { style: { paddingTop: pt(gap) }, attrs: { "data-gap-above": String(gap) } } : { style: {}, attrs: {} };
}
