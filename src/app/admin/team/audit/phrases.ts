/** Подробности записи одной строкой «было: …, стало: …»: плоские значения как есть, вложенное — сжато. */
export function detailsText(d: Record<string, unknown> | null | undefined): string {
  if (!d) return "";
  const part = (v: unknown): string => (v === null || v === undefined ? "—" : typeof v === "object" ? JSON.stringify(v) : String(v));
  return Object.entries(d)
    .map(([k, v]) => `${keyLabels[k] ?? k}: ${part(v)}`)
    .join(", ");
}
