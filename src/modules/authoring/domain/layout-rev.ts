/**
 * Переключатели выпуска правил раскладки фото (books.layout_rev, src/lib/book/layout.ts): 1 — прежние правила,
 * 2 — у каждого фото одно место (фото главы выбирает автор, снимки обложки внутрь сами не идут).
 *
 * Выпуск 1 (сейчас) — только схема, ядро, перевод и скрипт npm run photos:layout-rev2 (пробный проход): ни одна книга,
 * и новая, не меняется.
 * Выпуск 2 (интерфейс мест фото) переключает оба: новые книги — сразу на правилах 2, а книга на правилах 1 переходит
 * на них сама при первой правке мест фото, пакетной правке или смене оформления (та же транзакция, тот же перевод).
 */
export type LayoutRev = 1 | 2;

/** Правила новой книги (Book.start). Выпуск 2 — 2 (вместе с миграцией DEFAULT 2 у books.layout_rev). */
export const NEW_BOOK_LAYOUT_REV: LayoutRev = 1;

/** Переводить книгу на правила 2 при правке мест фото и смене оформления. Выпуск 2 — true. */
export const UPGRADE_ON_TOUCH: boolean = false;

/**
 * Перевод книг скриптом (npm run photos:layout-rev2 -- --apply) — только при включённом выпуске 2: иначе переведённые
 * книги жили бы по правилам 2 под интерфейсом, подсказками и счётчиком полос выпуска 1. Пробный проход и откат — всегда.
 */
export const LAYOUT_REV2_APPLY: boolean = (NEW_BOOK_LAYOUT_REV as LayoutRev) === 2 && UPGRADE_ON_TOUCH;
