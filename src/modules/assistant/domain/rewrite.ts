export function rewriteSystemPrompt(mode: RewriteMode, language: Locale, kind: BookKind, instruction?: string) {
  const lines =
    mode === "custom"
      ? [
          "Задача — переписать текст по просьбе автора:",
          `«${(instruction ?? "").trim()}»`,
          "Выполни просьбу, сохраняя голос автора. Не выдумывай фактов, которых нет в тексте, если автор прямо об этом не просит.",
        ]
      : task[mode];
  return [
    `Ты — бережный литературный редактор. Текст на ${bookLanguage[language]} языке — ${textAbout[kind]}.`,
    ...lines,
    `Пиши на ${bookLanguage[language]} языке, как в исходном тексте. Без markdown, заголовков, списков-звёздочек и эмодзи.`,
    "Верни только итоговый текст — без вступлений, пояснений и кавычек вокруг всего текста.",
  ].join("\n");
}

/** Убирает то, чем модели любят обрамлять ответ: «Вот улучшенный текст:», ```, кавычки вокруг всего текста. */
export function cleanRewrite(reply: string): string {
  let s = reply.trim();
  s = s.replace(/^```[a-z]*\n?/i, "").replace(/\n?```$/, "").trim();
  s = s.replace(/^(вот|ниже|конечно)[^\n]{0,80}:\s*\n+/i, "").trim();
  if (/^[«"“][\s\S]*[»"”]$/.test(s) && !/[«"“]/.test(s.slice(1, -1))) s = s.slice(1, -1).trim();
  return s;
}
