/** «сколько стоит доставка» — это вопрос о доставке, а не о цене книги. */
const DELIVERY_PRICE = rx(["(?:стоит|стоимость|цена|платн\\S*|сколько)\\s+(?:\\S+\\s+)?доставк", "доставк\\S*\\s+(?:\\S+\\s+)?(?:стоит|платн|сколько|отдельно)", "жеткіз\\S*\\s+(?:\\S+\\s+)?(?:қанша|канша|тегін|бағасы)"]);

/** Частые вопросы в сообщении — в порядке FAQ_INTENTS. */
export function faqIntents(text: string): FaqIntent[] {
  const t = norm(text);
  const found = FAQ_INTENTS.filter((i) => FAQ[i].test(t));
  // «доставка оплачивается отдельно?» — про доставку; «оплата» в нём — не вопрос об оплате книги.
  if (found.includes("delivery") && DELIVERY_PRICE.test(t)) return found.filter((i) => i !== "price" && i !== "payment");
  return found;
}

