/**
 * Бот-квалификатор: понимание сообщений клиента без сети и БД — язык, намерения (цена, доставка, сроки…), просьбы
 * позвать человека, «не знаю», даты и варианты ответов. Словари — по реальной переписке клиентов на русском и казахском
 * (в том числе казахский без казахских букв: «туган кунге», «рахмет»). Покрыто тестами tests/bot-engine.test.ts.
 */

export type BotLang = "ru" | "kk";

/** Частые вопросы, на которые бот отвечает шаблоном из настроек. */
export type FaqIntent = "price" | "delivery" | "timing" | "how" | "payment" | "examples" | "language";
export const FAQ_INTENTS: readonly FaqIntent[] = ["price", "how", "timing", "delivery", "payment", "examples", "language"];

/** Просьбы, после которых бот замолкает и зовёт человека. */
export type HandoffKind = "call" | "manager" | "paid" | "pay" | "complaint";

/** Граница слова для кириллицы (\b в JS понимает только латиницу). */
const B = "(?:(?<![\\p{L}\\p{N}])(?=[\\p{L}\\p{N}])|(?<=[\\p{L}\\p{N}])(?![\\p{L}\\p{N}]))";
/** Регулярка с \b, работающим для русских и казахских слов. */
export const rx = (src: string | readonly string[]) => new RegExp((typeof src === "string" ? src : src.join("|")).replaceAll("\\b", B), "iu");

/** Нижний регистр, ё → е, латинская i внутри кириллического слова → казахская і, без вариационных селекторов эмодзи. */
export function norm(text: string) {
  return text
    .toLowerCase()
    .replace(/ё/g, "е")
    .replace(/[\u200d\ufe0f]/g, "")
    .replace(/(?<=[а-яәғқңөұүһі])i|i(?=[а-яәғқңөұүһі])/g, "і")
    .replace(/\s+/g, " ")
    .trim();
}

const KK_LETTERS = /[әғқңөұүһі]/;
const KK_WORDS = rx([
  "\\bсәлем", "\\bсалем(?:етсіз|етсиз)?\\b", "\\bсаламатсыз", "\\bсалеметсиз", "\\bрахмет", "\\bрақмет", "\\bиә\\b", "\\bия\\b", "\\bжоқ\\b", "\\bжок\\b", "\\bканша\\b", "\\bкалай\\b",
  "\\bкерек\\b", "\\bбар\\s+ма\\b", "\\bкітап", "\\bкитап", "\\bтуган\\s+кун", "\\bмаган\\b", "\\bсизге\\b", "\\bсізге\\b", "\\bжаксы\\b", "\\bбола\\s+ма\\b", "\\bмен\\s+(?:сізге|сизге)\\b",
]);

/** Язык сообщения: казахский — по казахским буквам или словам; без букв (цифра, эмодзи) — null. */
export function detectLang(text: string): BotLang | null {
  const t = norm(text);
  if (!/\p{L}/u.test(t)) return null;
  return KK_LETTERS.test(t) || KK_WORDS.test(t) ? "kk" : "ru";
}

const ASK_KK = rx(["на\\s+казахском", "по[\\s-]?казахски", "казахском\\s+языке", "\\bқазақша", "\\bказакша", "қазақ\\s+тілінде", "казак\\s+тилинде", "қазақ\\s+тілі"]);
const ASK_RU = rx(["на\\s+русском", "по[\\s-]?русски", "\\bорысша", "орыс\\s+тілінде"]);

/** Клиент прямо просит общаться на другом языке («можно на казахском?», «орысша»). */
export function langRequest(text: string): BotLang | null {
  const t = norm(text);
  if (ASK_KK.test(t)) return "kk";
  if (ASK_RU.test(t)) return "ru";
  return null;
}

