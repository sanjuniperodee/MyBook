/** Просьба, после которой нужен человек; первая по важности (оплата и жалоба важнее звонка). */
export function handoffIntent(text: string): HandoffKind | null {
  const t = norm(text);
  return HANDOFF.find(([, re]) => re.test(t))?.[0] ?? null;
}

const STOP = rx(["^(?:стоп|хватит|прекратите)\\b", "\\bне\\s+(?:пишите|пиши|беспокойте|звоните)\\b", "\\bотстаньте\\b", "\\bотпишите(?:сь)?\\b", "\\bжазбаңыз\\b", "\\bмазаламаңыз\\b", "\\bтоқтатыңыз\\b"]);
/** «Стоп», «не пишите мне» — клиент просит замолчать: это не ответ на вопрос бота. */
export const isStop = (text: string) => STOP.test(norm(text));

/**
 * После просьбы до конца сообщения — только эти слова и знаки: «не пишите мне больше, пожалуйста», «не пишите на этот
 * номер», «маған енді жазбаңыз, рахмет». Любое другое продолжение («…, пишите в WhatsApp», «… пока, я на работе»,
 * «… варианты, беру второй») — уже не просьба больше не писать.
 */
const NO_MSG_TAIL =
  "(?:[\\s,]+(?:мне|меня|нам|сюда|здесь|больше|пожалуйста|пжл|вообще|никогда|уже|спасибо|сообщения|рассылку|ничего|на\\s+(?:этот|мой|данный)\\s+номер|по\\s+этому\\s+номеру|в\\s+(?:ватсап|ватсапп|вотсап|вацап|whatsapp|watsapp)|енді|енди|мүлдем|мулдем|ешқашан|ешкашан|өтінемін|отинемин|рахмет|рақмет))*";
/** Конец сообщения: точка, «!», скобка-смайлик; вопрос («почему не пишите?») — не просьба. */
const NO_MSG_END = "[\\s.!)(…]*$";
const NO_MSG_RU_VERB = "(?:пишите|пиши|присылайте|присылай|беспокойте|беспокой)";
const NO_MSG_RU_INF = "(?:писать|присылать|слать|беспокоить|спамить)";
/** «маған» — и без казахских букв («маган»), и разговорное «мага». */
const KK_TO_ME = "ма(?:ғ|г)а(?:н)?";
/** «енді», «бұдан былай» — «больше», «впредь». */
const KK_ANYMORE = "(?:енд(?:і|и)|б(?:ұ|у)дан\\s+былай)";
const KK_DONT_WRITE = "жазба(?:(?:ң|н)ыз(?:дар)?(?:шы)?|(?:ң|н)дар)?";
const KK_DONT_SEND = "(?:хабарлама\\s+)?ж(?:і|и)берме(?:ң|н)(?:і|и)з";

/**
 * Клиент просит больше ему не писать: «не пишите мне», «прошу больше не писать», «не надо мне писать», «хватит мне
 * писать», «отпишите меня», «удалите мой номер», «стоп» отдельным сообщением, «маған (енді) жазбаңыз» — и без казахских
 * букв («маган енди жазбаныз»), «мазаламаңыз». Такой номер CRM сама ставит в стоп-лист «Не писать первым» — молча и
 * надолго, поэтому шаблоны узкие: просьба — до конца сообщения (см. NO_MSG_TAIL). Уже, чем isStop: «не пишите имя на
 * обложке», «не пишите мне сюда, пишите в WhatsApp», «не пиши мне пока, я на работе», «хватит» (ответ на «ещё фото?»),
 * «хватит присылать варианты, беру второй», «удалите номер страницы», «отпишитесь, как получите» и «стоп, я передумала»
 * сюда не попадают.
 */
const NO_MESSAGES = rx([
  `\\bне\\s+${NO_MSG_RU_VERB}${NO_MSG_TAIL}${NO_MSG_END}`,
  `\\b(?:не\\s+(?:надо|нужно)|прошу\\s+(?:вас\\s+)?(?:больше\\s+)?не|просьба\\s+(?:больше\\s+)?не|больше\\s+не)\\s+(?:мне\\s+)?(?:больше\\s+)?(?:ничего\\s+)?${NO_MSG_RU_INF}${NO_MSG_TAIL}${NO_MSG_END}`,
  `\\b(?:хватит|перестаньте|перестань|прекратите|прекрати)\\s+(?:мне\\s+)?${NO_MSG_RU_INF}${NO_MSG_TAIL}${NO_MSG_END}`,
  "\\bотстаньте\\b",
  "\\bотпишите\\s+меня\\b",
  "\\bудалите\\s+(?:мой\\s+номер|номер|меня)\\s+из\\s+(?:вашей\\s+)?(?:базы|рассылки|списка|контактов)\\b",
  `\\bудалите\\s+(?:мой\\s+)?номер${NO_MSG_TAIL}${NO_MSG_END}`,
  `^(?:стоп|stop|прекратите)${NO_MSG_END}`,
  `\\b${KK_TO_ME}\\s+(?:${KK_ANYMORE}\\s+)?(?:${KK_DONT_WRITE}|${KK_DONT_SEND})${NO_MSG_TAIL}${NO_MSG_END}`,
  `\\b${KK_ANYMORE}\\s+(?:${KK_TO_ME}\\s+)?(?:${KK_DONT_WRITE}|${KK_DONT_SEND})${NO_MSG_TAIL}${NO_MSG_END}`,
  `^жазба(?:ң|н)ыз(?:дар)?(?:шы)?${NO_MSG_TAIL}${NO_MSG_END}`,
  "\\bмазалама(?:ң|н)ыз",
]);
/**
 * Похоже на просьбу, но нет: «почему вы мне не пишите» (жалоба на тишину, «пишите» вместо «пишете»), «пока / сейчас не
 * пишите» (подождать), «пишите в WhatsApp, сюда не пишите» (писать в другое место — из виджета сайта это просьба писать
 * на тот самый номер WhatsApp, который иначе попал бы в стоп-лист).
 */
const NO_MESSAGES_NOT = rx([
  "\\b(?:почему|чего)\\s+(?:\\S+\\s+){0,2}не\\s+(?:пиш|присыл)",
  "\\b(?:пока|сейчас|сегодня|временно)\\s+(?:мне\\s+)?не\\s+(?:пиш|присыл|беспоко)",
  "(?<!не\\s)\\bпиш(?:ите|и)\\s+(?:мне\\s+)?(?:в|во|на)\\b",
]);
/** Просьба больше не писать клиенту — номер в стоп-лист «Не писать первым». */
export function asksNoMessages(text: string) {
  const t = norm(text).replace(/\p{Extended_Pictographic}/gu, "").trim();
  return NO_MESSAGES.test(t) && !NO_MESSAGES_NOT.test(t);
}

const DECLINE = rx(["^(?:спасибо,?\\s*)?не\\s+(?:интересует|надо|нужно|актуально)", "\\bпередумал[аи]?\\b", "\\bуже\\s+не\\s+(?:надо|нужно|актуально)", "\\bкерек\\s+емес", "\\bқажет\\s+емес", "\\bқызықтырмайды"]);
/** «Не интересует», «уже не надо». */
export const isDecline = (text: string) => DECLINE.test(norm(text)) || isStop(text);

const DONT_KNOW = rx([
  "\\bне\\s+зна(?:ю|ем|ет)\\b", "\\bпока\\s+не\\s+(?:решил|решила|решили|определил|определилась|определились)", "\\bзатрудня", "\\bбез\\s+разницы\\b", "\\bпропуст", "\\bне\\s+важно\\b", "\\bпотом\\s+(?:скажу|решу|решим)", "\\bпозже\\s+(?:скажу|решу)",
  "\\bбілмеймін", "\\bбилмеймин", "\\bбілмейміз", "\\bәлі\\s+(?:білмеймін|шешкен\\s+жоқпын|шешпедім|шешпедік)", "\\bкейін\\s+(?:айтамын|айтам|шешемін)", "\\bбелгісіз", "\\bмаңызды\\s+емес",
]);
/** «Не знаю», «пока не решила», «білмеймін» — ответа на вопрос пока нет. */
export const isDontKnow = (text: string) => DONT_KNOW.test(norm(text));

const GREETING = rx([
  "\\bздравствуй", "\\bздрасьте", "\\bдобр(?:ый|ое|ого)\\s+(?:день|вечер|утро|дня|вечера|утра)", "\\bпривет", "\\bсалам\\b", "\\bсалем", "\\bассалам", "\\bсәлем", "\\bсаламатсыз", "\\bсалеметсиз", "\\bқайырлы\\s+(?:күн|таң|кеш)",
]);
export const hasGreeting = (text: string) => GREETING.test(norm(text));
/** Сообщение — только приветствие («Здравствуйте!», «Добрый вечер», «Сәлеметсіз бе») без вопроса и ответа. */
const GREETING_ONLY =
  /^(?:здравствуйте|здравствуй|здрасьте|добр(?:ый|ое|ого)\s+(?:день|вечер|утро|дня|вечера|утра)|доброй\s+ночи|привет(?:ствую)?|салам|салем|сәлеметсіз\s*бе|салеметсиз\s*бе|саламатсыз\s*ба|сәлем|ассалаумағалейкум|ассалам\S*|қайырлы\s+(?:күн|таң|кеш))[\s!.,)(]*$/iu;
export const isGreetingOnly = (text: string) =>
  GREETING_ONLY.test(
    norm(text)
      .replace(/[\p{Extended_Pictographic}]/gu, "")
      .trim(),
  );

/** Короткие ответы-подтверждения: «да», «ок», «спасибо», «рақмет» — продолжение разговора, а не новый вопрос. */
const ACK_WORDS = new Set([
  "да", "нет", "ок", "окей", "ok", "okay", "хорошо", "ладно", "понятно", "понятно спасибо", "спасибо", "спасибо большое", "ага", "угу", "ясно", "супер", "отлично", "договорились", "давайте", "конечно", "благодарю",
  "жақсы", "жаксы", "иә", "иа", "ия", "жоқ", "жок", "рақмет", "рахмет", "үлкен рақмет", "түсіндім", "тусиндим", "түсінікті", "мақұл", "макул", "келістік", "болады", "+",
]);
export function isAck(text: string) {
  const t = norm(text).replace(/[^\p{L}\p{N}+ ]/gu, " ").replace(/\s+/g, " ").trim();
  return !t || ACK_WORDS.has(t);
}

/** Слова, которые говорят, что человек пришёл с новым вопросом, а не продолжает старую переписку. */
const NEW_REQUEST = rx(["\\bкниг", "\\bкітап", "\\bкитап", "\\bхочу\\b", "\\bхотел[аи]?\\b", "\\bинтерес", "\\bподскаж", "\\bузнать\\b", "\\bможно\\b", "\\bподар", "\\bсыйлық", "\\bсыйлык", "\\bкерек\\b", "\\bбола\\s+ма\\b", "\\bреклам"]);

/**
 * Первое сообщение похоже на продолжение старой переписки (её вели с телефона до CRM): «Ок», «Маме», «Да, спасибо».
 * Новый клиент пишет приветствие, вопрос или «хочу книгу».
 */
export function looksLikeContinuation(text: string) {
  const t = norm(text);
  if (!t) return false;
  if (isAck(t) || handoffIntent(t) === "paid") return true;
  if (hasGreeting(t) || faqIntents(t).length || handoffIntent(t) || t.includes("?") || NEW_REQUEST.test(t)) return false;
  return t.split(/\s+/).filter((w) => /\p{L}/u.test(w)).length <= 3;
}

/** Отрицание с понятием: «не нужно электронную», «не хочу печатную», «без свадьбы», «электронды керек емес». */
const NEGATED = rx(["\\bне\\s+(?:нужн\\S*|надо|хочу|хотим|хотелось\\s+бы)\\s+\\S+", "\\bбез\\s+\\S+", "\\S+\\s+(?:керек|қажет|кажет)\\s+емес"]).source;
const NEGATED_RE = new RegExp(NEGATED, "giu");

/** Понятия в ответах на вопросы-списки: повод и формат. Вариант списка сопоставляется с ними по своему тексту. */
const CONCEPTS: [string, RegExp][] = [
  ["unknown", DONT_KNOW],
  ["feb14", rx(["\\b14\\s*(?:-?(?:го|е|ое|ші|і))?\\s*(?:феврал|ақпан|акпан)", "\\bвлюбленн", "\\bвалентин"])],
  ["mar8", rx(["\\b8\\s*(?:-?(?:го|е|ое|ші|і))?\\s*(?:март|наурыз)", "\\bженск\\S*\\s+(?:день|праздник)", "\\bхалықаралық\\s+әйелдер"])],
  ["newyear", rx(["\\bнов(?:ый|ому|ым|ого)\\s+год", "\\bнг\\b", "\\bжаңа\\s*жыл", "\\bжана\\s*жыл"])],
  ["birthday", rx(["\\bдн(?:ем|я|ю|е)?\\s+рождени", "\\bдень\\s+рождени", "\\bдр\\b", "\\bднюх", "\\bд\\.\\s?р\\.?", "\\bтуған\\s*күн", "\\bтуган\\s*кун", "\\bтуылған\\s+күн"])],
  ["anniversary", rx(["\\bгодовщин", "\\bгод\\s+(?:вместе|отношений|знакомства|свадьбы|брака)", "\\bлет\\s+(?:вместе|свадьбы|брака|отношений)", "\\bжылдығ", "\\bжылдык", "\\bжыл\\s+толу", "\\bтанысқанымыз", "\\bбірге\\s+болғанымыз", "\\bүйленгенімізге"])],
  ["wedding", rx(["\\bсвадь?б", "\\bсвадеб", "\\bбракосочет", "\\bүйлену\\s*то", "\\bуйлену\\s*то", "\\bқыз\\s*ұзату", "\\bкыз\\s*узату"])],
  ["jubilee", rx(["\\bюбиле", "\\bмерейто", "\\bмерей\\s+той"])],
  ["graduation", rx(["\\bвыпускн", "\\bбітіру", "\\bбитиру", "\\bтүлек", "\\bтулек"])],
  ["parents", rx(["\\bродител", "\\bата-?ана"])],
  ["other", rx(["\\bдруг(?:ой|ое|ие|ая)\\s+(?:повод|праздник)", "\\bдругой\\b", "\\bпросто\\s+так\\b", "\\bбез\\s+повода", "\\bбасқа\\b", "\\bбаска\\b", "\\bсебепсіз", "\\bжай\\s+ғана"])],
  ["printed", rx(["\\bпечатн", "\\bбумажн", "\\bтверд\\S*", "\\bпереплет", "\\bнапечат", "\\bраспечат", "\\bфизическ", "\\bнастоящ\\S*\\s+книг", "\\bв\\s+руках\\b", "\\bқатты\\s+мұқаба", "\\bкатты\\s+мукаба", "\\bқағаз", "\\bкагаз", "\\bбасылған", "\\bбаспа"])],
  ["digital", rx(["\\bэлектрон", "\\bpdf\\b", "\\bпдф\\b", "\\bцифров", "\\bонлайн", "\\bэлектрондық", "\\bэлектронды"])],
];

/** Понятия, найденные в тексте, с позицией первого совпадения. */
export function concepts(text: string): { id: string; at: number }[] {
  // Отрицание: «не нужно электронную, только печатную» — электронная отпадает; «без подарочной упаковки» — не выбор.
  const t = norm(text).replace(NEGATED_RE, " ");
  const out: { id: string; at: number }[] = [];
  for (const [id, re] of CONCEPTS) {
    const m = re.exec(t);
    if (m) out.push({ id, at: m.index });
  }
  return out;
}

/** Что осталось от сообщения без приветствия, вопросов о цене и т. п. — есть ли в нём попытка ответить. */
export function residual(text: string) {
  let t = norm(text);
  for (const re of [GREETING, ...Object.values(FAQ), ...HANDOFF.map(([, r]) => r)]) t = t.replace(new RegExp(re.source, "giu"), " ");
  return t.replace(/[^\p{L}\p{N}]+/gu, " ").replace(/\s+/g, " ").trim();
}

/** Возражения после предложения: цена («дорого», «ақша жоқ») и «потом» («подумаю», «во вторник оплачу», «ертең»). */
export type Objection = "price" | "later";

const OBJECTION: [Objection, RegExp][] = [
  ["price", rx(["\\bдорог", "\\bнет\\s+денег", "\\bденег\\s+(?:нет|пока\\s+нет|не\\s+хватает)", "\\bне\\s+потян", "\\bне\\s+по\\s+карману", "\\bбюджет", "\\bподешевле", "\\bдешевле", "\\bқымбат", "\\bкымбат", "\\bақша(?:м)?\\s+жоқ", "\\bакша(?:м)?\\s+жок", "\\bақша\\s+(?:болмай|жетпей)", "\\bарзанырақ"])],
  ["later", rx([
    "\\bподума(?:ю|ть|ем|л[аи]?)\\b", "\\bпосовету(?:юсь|емся)", "\\bпозже\\b", "\\bпотом\\b", "\\bзавтра\\b", "\\bпослезавтра\\b", "\\bзарплат", "\\bна\\s+следующей\\s+неделе", "\\bв\\s+следующем\\s+месяце",
    "\\b(?:в|во)\\s+(?:понедельник|вторник|среду|четверг|пятницу|субботу|воскресенье)\\b", "\\bсам(?:а)?\\s+напишу", "\\bнапишу\\s+(?:сам|сама|позже|вам)", "\\bне\\s+сейчас\\b", "\\bпока\\s+не\\s+(?:готов|могу)",
    "\\bойлан", "\\bкейін\\b", "\\bкейінірек", "\\bертең\\b", "\\bертен\\b", "\\bайлық", "\\bкелесі\\s+(?:апта|ай)", "\\bөзім\\s+жазам", "\\bқазір\\s+емес",
  ])],
];

/** Возражение в ответ на предложение (первое по важности: цена важнее «потом»). */
export function objectionKind(text: string): Objection | null {
  const t = norm(text);
  return OBJECTION.find(([, re]) => re.test(t))?.[0] ?? null;
}

const AGREE = rx([
  "\\bдавайте\\b", "\\bдавай\\b", "\\bоформ(?:ляем|ляйте|им|ите|ить|лю)\\b", "\\bсоглас(?:ен|на|ны)\\b", "\\bбер(?:у|ем|ём)\\b", "\\bзаказываю\\b", "\\bхочу\\s+заказать",
  "\\bначн(?:ем|ём|им)\\b", "\\bначинаем\\b", "\\bприступ(?:им|аем)\\b", "\\bпоехали\\b", "\\bпогнали\\b", "\\bготов[аы]?\\b", "\\bвыставляйте\\b", "\\bприсылайте\\b", "\\bотправляйте\\b",
  "\\bкелістік\\b", "\\bбастайық\\b", "\\bбастаймыз\\b", "\\bтапсырыс\\s+(?:беремін|берем|береміз)", "\\bаламын\\b", "\\bалам\\b", "\\bжіберіңіз(?:ші)?\\b", "\\bдайынмын\\b",
]);
const NEGATION = new Set(["не", "ни", "нет", "неа", "емес", "жоқ", "жок", "болмайды"]);
const HEDGE = rx(["\\bуточн", "\\bобсуд", "\\bпосовету", "\\bпоговор", "\\bспрошу", "\\bузнаю", "\\bпозвон", "\\bсозвон", "\\bкейін\\b"]);
/** Короткое «да» целиком: «да», «ок, конечно», «иә жақсы». «Хорошо, сейчас посмотрю» — не согласие. */
const AGREE_WORDS = new Set(["да", "ага", "угу", "конечно", "го", "ок", "окей", "ok", "хорошо", "ладно", "можно", "супер", "отлично", "ну", "иә", "иа", "ия", "жақсы", "жаксы", "жарайды", "мақұл", "макул", "болды", "әрине", "+"]);

/**
 * Согласие на предложение: «да», «давайте», «оформляем», «иә, бастайық». Вопрос («да, а доставка?») и возражение
 * («да, но дорого») согласием не считаются — на них бот отвечает отдельно.
 */
export function isAgree(text: string) {
  const t = norm(text);
  if (!t || t.includes("?") || objectionKind(t) || isDecline(t) || /^\s*(?:нет|жоқ|жок)\b/u.test(t)) return false;
  const words = t.replace(/[^\p{L}\p{N}+ ]/gu, " ").split(" ").filter(Boolean);
  // «не готова», «не берём», «не присылайте», «қажет емес» и «давайте уточню у мужа» — не согласие.
  if (words.some((w) => NEGATION.has(w)) || HEDGE.test(t)) return false;
  return AGREE.test(t) || (words.length > 0 && words.every((w) => AGREE_WORDS.has(w)));
}

/** Отрицание или оговорка в тексте («не готова», «давайте уточню у мужа»): такое согласием не считается. */
export function isHedged(text: string) {
  const t = norm(text);
  const words = t.replace(/[^\p{L}\p{N}+ ]/gu, " ").split(" ").filter(Boolean);
  return words.some((w) => NEGATION.has(w)) || HEDGE.test(t);
}

/**
 * Прямая просьба оформить («оформляйте», «выставляйте счёт», «беру», «хочу заказать»): согласие даже тогда, когда бот
 * не спрашивал «Оформляем?». Вопрос, возражение, отказ, отрицание и оговорка («давайте уточню у мужа») — нет.
 */
export function hasOrderIntent(text: string) {
  const t = norm(text);
  if (!t || t.includes("?") || objectionKind(t) || isDecline(t)) return false;
  const words = t.replace(/[^\p{L}\p{N}+ ]/gu, " ").split(" ").filter(Boolean);
  if (words.some((w) => NEGATION.has(w)) || HEDGE.test(t)) return false;
  return AGREE.test(t);
}

/** «Нет» в ответ на «Оформляем?» — не отказ от книги, а «не сейчас». */
export const isBareNo = (text: string) => /^\s*(?:нет|не|неа|жоқ|жок|пока\s+нет)\s*[.!)]*\s*$/u.test(norm(text));

const WILL_LOOK = rx(["\\bознаком(?:люсь|имся|люсь)", "\\bпосмотр(?:ю|им)\\b", "\\bгляну\\b", "\\bизуч(?:у|им)\\b", "\\bпочитаю\\b", "\\bқарап\\s+(?:шығамын|шығам|көремін|көрем)", "\\bқараймын\\b", "\\bқарайын\\b", "\\bтанысып\\s+шығам"]);
/** «Хорошо, сейчас ознакомлюсь», «қарап шығамын» — клиент смотрит пример: не вопрос и не отказ, бот ждёт. */
export const isWillLook = (text: string) => WILL_LOOK.test(norm(text));
