/**
 * Служебная задача сделки «Получить остаток …» (заведение клиента с предоплатой, оплата счёта из чата): начало
 * заголовка — по нему её закрывают, когда остаток получен, — и итог закрытия. Один источник для сервера и CRM.
 */
export const REMAINDER_TASK_PREFIX = "Получить остаток ";

/** Итог закрытия: оплачен заказ (номер) или сделка оплачена полностью ручным платежом. */
export const remainderPaidResult = (orderNumber?: number | null) => (orderNumber ? `Остаток получен: заказ №${orderNumber} оплачен` : "Остаток получен: сделка оплачена полностью");

/** Запись в ленту сделки о закрытой задаче. */
export const remainderClosedNote = (orderNumber: number) => `Задача «${REMAINDER_TASK_PREFIX.trim()} …» закрыта: заказ №${orderNumber} оплачен`;
