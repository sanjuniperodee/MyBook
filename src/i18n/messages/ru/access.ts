import { ruCount } from "../../plural";

const hello = (name: string) => `Здравствуйте${name ? `, ${name}` : ""}!`;

/**
 * Доступ в личный кабинет после оплаты счёта из чата: сообщения клиенту в тот же WhatsApp-чат на языке счёта.
 * Ссылка «задайте пароль» уходит клиенту целиком, а в CRM хранится с маской.
 */
export const access = {
  /** Логин, когда клиент входит по номеру этого чата: сам номер в тексте не пишем — переписку видят менеджеры без доступа к номерам. */
  thisNumber: "номер этого WhatsApp",
  /** Аккаунт новый (заведён оплатой или ещё не использован): ссылка «задайте пароль» и логин. */
  setPassword: (i: { name: string; label: string; amount: string; link: string; login: string; hours: number }) =>
    [
      `${hello(i.name)} Оплата по счёту ${i.label} получена — ${i.amount}. Спасибо!`,
      "Ваш личный кабинет MyBooks готов: в нём вы напишете книгу.",
      `Задайте пароль и войдите: ${i.link}`,
      `Логин: ${i.login}`,
      `Ссылка действует ${ruCount(i.hours, "час", "часа", "часов")} и срабатывает один раз.`,
    ].join("\n"),
  /** Аккаунтом уже пользуются: войти как обычно; ссылки сброса в чате нет (номер мог перейти к другому человеку). */
  loginAsUsual: (i: { name: string; label: string; amount: string; loginUrl: string; login: string; emailMasked: string | null }) =>
    [
      `${hello(i.name)} Оплата по счёту ${i.label} получена — ${i.amount}. Спасибо!`,
      `Войдите в личный кабинет как обычно: ${i.loginUrl}`,
      `Логин: ${i.login}`,
      i.emailMasked ? `Если не помните пароль — ссылку, чтобы задать новый, мы отправили на ${i.emailMasked}.` : "Если не помните пароль — напишите нам здесь, поможем.",
    ].join("\n"),
  /** Доступ по этой книге уже выдан: следующая оплата — коротко. */
  paid: (i: { name: string; label: string; amount: string; loginUrl: string }) => `${hello(i.name)} Оплата по счёту ${i.label} получена — ${i.amount}. Спасибо! Личный кабинет: ${i.loginUrl}`,
  /** Чей аккаунт — решает менеджер: логин не раскрываем, доступ пришлёт он. */
  manager: (i: { name: string; label: string; amount: string }) => `${hello(i.name)} Оплата по счёту ${i.label} получена — ${i.amount}. Спасибо! Менеджер пришлёт вам доступ в личный кабинет.`,
};
